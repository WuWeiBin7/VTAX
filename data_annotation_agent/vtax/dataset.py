from __future__ import annotations

from collections import Counter, defaultdict
import csv
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import random
import re
import shutil
from typing import Any


IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff"}
SPLITS = ("train", "val", "test")


@dataclass(frozen=True, slots=True)
class SourceImage:
    image: Path
    root: Path
    role: str
    dataset: str


def prepare_yolo_dataset(
    source: Path,
    output: Path,
    labels: list[str],
    *,
    replay_sources: list[Path] | None = None,
    replay_ratio: float = 0.4,
    seed: int = 42,
    ratios: tuple[float, float, float] = (0.8, 0.15, 0.05),
) -> dict[str, Any]:
    source = source.resolve()
    output = output.resolve()
    if not source.is_dir():
        raise FileNotFoundError(f"Annotation directory does not exist: {source}")
    if not labels or len(labels) != len(set(labels)):
        raise ValueError("Detection labels must be non-empty and unique")
    if any(value < 0 for value in ratios) or abs(sum(ratios) - 1.0) > 1e-6:
        raise ValueError("train/val/test ratios must be non-negative and total 1")
    if not 0 <= replay_ratio <= 1:
        raise ValueError("Replay ratio must be between 0 and 1")
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"Dataset output already exists and is not empty: {output}")

    new_images = _source_images(source, "new", source.name)
    if not new_images:
        raise ValueError(f"No supported images found under {source}")
    replay_candidates: list[SourceImage] = []
    seen_replay: set[Path] = set()
    for replay_source in replay_sources or []:
        replay_root = replay_source.resolve()
        for item in _source_images(replay_root, "replay", replay_root.name):
            resolved = item.image.resolve()
            if resolved not in seen_replay:
                replay_candidates.append(item)
                seen_replay.add(resolved)
    replay_target = min(len(replay_candidates), round(len(new_images) * replay_ratio))
    rng = random.Random(seed)
    replay_candidates.sort(key=lambda item: str(item.image))
    replay_images = rng.sample(replay_candidates, replay_target) if replay_target else []
    images = [*new_images, *replay_images]
    provenance_by_root = {item.root: _read_provenance(item.root) for item in images}
    groups: dict[str, list[Path]] = defaultdict(list)
    group_for_image: dict[Path, str] = {}
    for item in images:
        group = f"{item.dataset}:{_group_for(item.image, item.root, provenance_by_root[item.root])}"
        group_for_image[item.image] = group
        groups[group].append(item.image)

    ratio_map = dict(zip(SPLITS, ratios, strict=True))
    group_assignments = assign_groups(groups, ratio_map, seed)
    positive_splits = [split for split in SPLITS if ratio_map[split] > 0]
    fallback_split = len(groups) < len(positive_splits)
    if fallback_split:
        image_assignments = assign_contiguous_images(groups, ratio_map, seed)
    else:
        image_assignments = {
            image: group_assignments[group]
            for group, paths in groups.items()
            for image in paths
        }
    for split in SPLITS:
        (output / "images" / split).mkdir(parents=True, exist_ok=True)
        (output / "labels" / split).mkdir(parents=True, exist_ok=True)

    class_ids = {label: index for index, label in enumerate(labels)}
    image_counts: Counter[str] = Counter()
    box_counts: Counter[str] = Counter()
    negative_counts: Counter[str] = Counter()
    class_counts: Counter[str] = Counter()
    rows: list[dict[str, Any]] = []
    for item in images:
        image = item.image
        relative = image.relative_to(item.root)
        group = group_for_image[image]
        split = image_assignments[image]
        annotation = json.loads(image.with_suffix(".json").read_text(encoding="utf-8-sig"))
        lines, counts = labelme_to_yolo(annotation, class_ids, image.with_suffix(".json"))
        target_name = _unique_name(Path(item.dataset) / relative)
        _link_or_copy(image, output / "images" / split / target_name)
        label_path = output / "labels" / split / f"{Path(target_name).stem}.txt"
        label_path.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
        image_counts[split] += 1
        box_counts[split] += len(lines)
        negative_counts[split] += int(not lines)
        class_counts.update(counts)
        rows.append({"source": str(image), "target": target_name, "role": item.role,
                     "dataset": item.dataset, "group": group, "split": split, "boxes": len(lines)})

    yaml_path = output / "dataset.yaml"
    yaml_lines = [
        "# Generated by VTAX. Source-video groups never cross dataset splits.",
        f"path: {output.as_posix()}",
        "train: images/train",
        "val: images/val",
        "test: images/test",
        "",
        "names:",
        *[f"  {index}: {json.dumps(label, ensure_ascii=False)}" for index, label in enumerate(labels)],
        "",
    ]
    yaml_path.write_text("\n".join(yaml_lines), encoding="utf-8")
    with (output / "manifest.csv").open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=("source", "target", "role", "dataset", "group", "split", "boxes"))
        writer.writeheader()
        writer.writerows(rows)
    summary = {
        "source_images": len(images),
        "new_images": len(new_images),
        "replay_images": len(replay_images),
        "replay_candidates": len(replay_candidates),
        "replay_ratio": replay_ratio,
        "new_dataset": str(source),
        "replay_datasets": [str(path.resolve()) for path in replay_sources or []],
        "source_groups": len(groups),
        "split_strategy": "contiguous_fallback" if fallback_split else "source_group",
        "split_warning": (
            "Source groups were fewer than non-empty splits; images were split into contiguous "
            "ordered ranges so train/val/test remain usable without random adjacent-frame mixing."
            if fallback_split else None
        ),
        "labels": labels,
        "splits": {
            split: {"images": image_counts[split], "boxes": box_counts[split], "negative_images": negative_counts[split]}
            for split in SPLITS
        },
        "class_counts": dict(class_counts),
        "seed": seed,
        "ratios": dict(zip(SPLITS, ratios, strict=True)),
        "yaml": str(yaml_path),
    }
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return summary


def _source_images(root: Path, role: str, dataset: str) -> list[SourceImage]:
    root = root.resolve()
    if not root.is_dir():
        raise FileNotFoundError(f"Labeled dataset directory does not exist: {root}")
    images = sorted(
        path for path in root.rglob("*")
        if path.is_file() and path.suffix.lower() in IMAGE_EXTENSIONS
    )
    for image in images:
        if not image.with_suffix(".json").is_file():
            raise FileNotFoundError(f"Missing LabelMe JSON for {image}")
    return [SourceImage(image=image, root=root, role=role, dataset=dataset) for image in images]


def labelme_to_yolo(
    annotation: dict[str, Any], class_ids: dict[str, int], annotation_path: Path
) -> tuple[list[str], Counter[str]]:
    width = float(annotation.get("imageWidth") or 0)
    height = float(annotation.get("imageHeight") or 0)
    if width <= 0 or height <= 0:
        raise ValueError(f"Invalid image dimensions in {annotation_path}")
    lines: list[str] = []
    counts: Counter[str] = Counter()
    for shape in annotation.get("shapes", []):
        label = str(shape.get("label", "")).strip()
        if label not in class_ids:
            raise ValueError(f"Unexpected label {label!r} in {annotation_path}; allowed: {list(class_ids)}")
        if shape.get("shape_type", "rectangle") != "rectangle":
            raise ValueError(f"Only rectangle shapes are supported: {annotation_path}")
        points = shape.get("points") or []
        if len(points) < 2:
            continue
        xs = [float(point[0]) for point in points]
        ys = [float(point[1]) for point in points]
        x1, x2 = max(0.0, min(xs)), min(width, max(xs))
        y1, y2 = max(0.0, min(ys)), min(height, max(ys))
        if x2 <= x1 or y2 <= y1:
            continue
        xc = (x1 + x2) / (2 * width)
        yc = (y1 + y2) / (2 * height)
        bw = (x2 - x1) / width
        bh = (y2 - y1) / height
        lines.append(f"{class_ids[label]} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}")
        counts[label] += 1
    return lines, counts


def assign_groups(groups: dict[str, list[Path]], ratios: dict[str, float], seed: int) -> dict[str, str]:
    rng = random.Random(seed)
    items = list(groups.items())
    rng.shuffle(items)
    items.sort(key=lambda item: len(item[1]), reverse=True)
    total = sum(len(paths) for _, paths in items)
    targets = {name: total * ratios[name] for name in SPLITS}
    assigned: Counter[str] = Counter()
    result: dict[str, str] = {}
    for group, paths in items:
        split = min(SPLITS, key=lambda name: (assigned[name] - targets[name], assigned[name], SPLITS.index(name)))
        result[group] = split
        assigned[split] += len(paths)
    return result


def assign_contiguous_images(
    groups: dict[str, list[Path]], ratios: dict[str, float], seed: int
) -> dict[Path, str]:
    """Fallback for too few source groups, using contiguous rather than random frame splits."""
    group_items = sorted(groups.items())
    random.Random(seed).shuffle(group_items)
    ordered = [path for _, paths in group_items for path in sorted(paths)]
    positive = [split for split in SPLITS if ratios[split] > 0]
    if len(ordered) < len(positive):
        raise ValueError(
            f"At least {len(positive)} images are required for non-empty "
            f"{'/'.join(positive)} splits; found {len(ordered)}"
        )
    raw = {split: len(ordered) * ratios[split] for split in SPLITS}
    counts = {split: int(raw[split]) for split in SPLITS}
    remaining = len(ordered) - sum(counts.values())
    for split in sorted(SPLITS, key=lambda name: (raw[name] - counts[name], -SPLITS.index(name)), reverse=True):
        if remaining <= 0:
            break
        counts[split] += 1
        remaining -= 1
    for split in positive:
        if counts[split] > 0:
            continue
        donor = max(positive, key=lambda name: counts[name])
        if counts[donor] <= 1:
            raise ValueError("Unable to create non-empty dataset splits")
        counts[donor] -= 1
        counts[split] = 1
    assignments: dict[Path, str] = {}
    offset = 0
    for split in SPLITS:
        limit = offset + counts[split]
        for image in ordered[offset:limit]:
            assignments[image] = split
        offset = limit
    return assignments


def _read_provenance(source: Path) -> dict[str, str]:
    path = source / "provenance.jsonl"
    if not path.is_file():
        return {}
    result: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if row.get("target") and row.get("source_video"):
            result[str(row["target"])] = str(row["source_video"])
    return result


def _group_for(image: Path, source: Path, provenance: dict[str, str]) -> str:
    relative = image.relative_to(source).as_posix()
    if relative in provenance:
        return provenance[relative]
    if image.name in provenance:
        return provenance[image.name]
    if image.parent != source:
        return image.parent.relative_to(source).as_posix()
    stem = re.sub(r"_(?:frame_)?\d+(?:_\d+(?:\.\d+)?s)?$", "", image.stem, flags=re.IGNORECASE)
    return stem or image.stem


def _unique_name(relative: Path) -> str:
    if len(relative.parts) == 1:
        return relative.name
    digest = hashlib.sha1(relative.as_posix().encode("utf-8"), usedforsecurity=False).hexdigest()[:10]
    return f"{relative.stem}_{digest}{relative.suffix.lower()}"


def _link_or_copy(source: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    try:
        target.hardlink_to(source)
    except OSError:
        shutil.copy2(source, target)
